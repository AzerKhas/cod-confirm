"""Write docs/whatsapp-templates.md from app/services/messages.py (single source of truth).

python -m scripts.export_templates
"""

from __future__ import annotations

from pathlib import Path

from app.config import get_settings
from app.enums import Language
from app.services.messages import TEMPLATES
from app.services.notify import template_language_code

OUT = Path(__file__).resolve().parent.parent / "docs" / "whatsapp-templates.md"
LANG_LABEL = {Language.DARIJA: "Tunisian Darija (Latin)", Language.ARABIC: "Arabic",
              Language.FRENCH: "French"}  # fmt: skip


def render() -> str:
    settings = get_settings()
    lines = [
        "# WhatsApp templates to submit to Meta",
        "",
        "Generated by `python -m scripts.export_templates` from `app/services/messages.py`.",
        "Do not edit by hand.",
        "",
        "Create them in **WhatsApp Manager → Message templates → Create template**,",
        "category **Utility**, exactly with the names, languages and texts below.",
        "",
        "> Meta has no *Darija* language. Latin-script Darija templates are registered under",
        f"> the language code `{settings.whatsapp_darija_template_language}` (setting "
        "`WHATSAPP_DARIJA_TEMPLATE_LANGUAGE`).",
        "> If a reviewer rejects one for language mismatch, resubmit it under another code",
        "> (e.g. `ar`) and change that setting.",
        "",
    ]
    for tpl in TEMPLATES:
        lines += [f"## `{tpl.key}`", "", "| # | Variable | Sample |", "|---|---|---|"]
        lines += [f"| {{{{{i}}}}} | {v} | {s} |" for i, (v, s) in
                  enumerate(zip(tpl.variables, tpl.samples, strict=True), 1)]  # fmt: skip
        lines.append("")
        for lang in Language:
            lines += [
                f"### {LANG_LABEL[lang]}",
                "",
                f"- **Name:** `{tpl.name(lang)}`",
                f"- **Language:** `{template_language_code(lang, settings)}`",
                f"- **Category:** {tpl.category}",
                "",
                "**Body**",
                "",
                "```",
                tpl.bodies[lang],
                "```",
                "",
            ]
            if tpl.footers.get(lang):
                lines += [f"**Footer:** {tpl.footers[lang]}", ""]
            if tpl.buttons.get(lang):
                lines += ["**Buttons (Quick reply, in this order):**", ""]
                lines += [f"{i}. {b}" for i, b in enumerate(tpl.buttons[lang], 1)]
                lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")
    print(f"written {OUT}")


if __name__ == "__main__":
    main()
